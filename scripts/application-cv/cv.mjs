// The application CV as a `docx` document (V1-21.2): the style sheet, the first-page block, the body and the footer of
// V1-20 put together, with the properties of the file. It reads nothing and writes nothing; `generate.mjs` does the files.
import { Document } from 'docx';
import { buildBody } from './body.mjs';
import { buildFirstBlock, buildFooter } from './header.mjs';
import { createStyles, PAGE } from './styles.mjs';

/** What the dry run writes in place of the phone number. It is not a number, so it stays plain text in the file. */
export const PHONE_ON_REQUEST = '(phone on request)';

/** The title, author and description of the file, as Word shows them under File > Info. */
export const PROPERTIES = {
  title: 'Truong Tan Khanh, CV',
  creator: 'Truong Tan Khanh',
  description: 'Application edition of the CV, generated by scripts/build-application-cv.mjs',
};

/**
 * The name of the file: the public CV's name with `.docx`, so the two editions are known by one name. It has to be
 * ASCII, because it is attached to an email and opened on machines that mangle other characters.
 */
export function fileName(resume) {
  const name = resume.cvPdf.replace(/\.pdf$/, '.docx');
  if (name === resume.cvPdf || !/^[\w.-]+$/.test(name))
    throw new Error(`Cannot make a .docx name from ${resume.cvPdf}`);
  return name;
}

/**
 * @param {{ resume: object, phone: string, logo: Buffer, font?: string }} input `phone` is the number from
 *   `cv/private.json`, or `PHONE_ON_REQUEST` in a dry run; `logo` is the content of `LOGO_FILE`; `font` is a font of
 *   `FONT` in `styles.mjs` and is Calibri unless given.
 */
export function buildCvDocument({ resume, phone, logo, font }) {
  return new Document({
    ...createStyles({ font }),
    ...PROPERTIES,
    sections: [
      {
        properties: { page: PAGE },
        footers: { default: buildFooter({ resume }) },
        children: [...buildFirstBlock({ resume, phone, logo }), ...buildBody(resume)],
      },
    ],
  });
}
