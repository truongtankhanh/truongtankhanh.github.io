// The application edition in one file (V1-23.1): the CV, then the project portfolio, for the sites that take one file
// only. It is the CV of `cv.mjs` and the body of `portfolio.mjs` put in one section, so the first block is written once,
// the footer counts the pages of the whole file, and the portfolio starts on a new page under a title of its own.
//
// Nothing is written twice: the words come from the same builders as the two separate files, and the phone number is in
// the contact line of the first page and nowhere else.
import { Document, Paragraph, TextRun } from 'docx';
import { buildBody } from './body.mjs';
import { buildFirstBlock, buildFooter } from './header.mjs';
import { buildPortfolioBody, PORTFOLIO_TITLE } from './portfolio.mjs';
import { createStyles, PAGE, STYLE } from './styles.mjs';

/** The title that starts the portfolio part; the check finds the two parts of the file by this paragraph. */
export const PART_TITLE = PORTFOLIO_TITLE;

export const COMBINED_PROPERTIES = {
  title: 'Truong Tan Khanh, CV and Project Portfolio',
  creator: 'Truong Tan Khanh',
  description:
    'Application edition of the CV with its project portfolio in one file, generated by scripts/build-application-cv.mjs',
};

/** The name of the file: the public CV's name with `_CV.pdf` replaced, so the editions sit side by side. ASCII only. */
export function combinedFileName(resume) {
  const name = resume.cvPdf.replace(/_CV\.pdf$/, '_CV_and_Portfolio.docx');
  if (name === resume.cvPdf || !/^[\w.-]+$/.test(name)) {
    throw new Error(`Cannot make a combined file name from ${resume.cvPdf}`);
  }
  return name;
}

/**
 * @param {{ resume: object, phone: string, logo: Buffer, projects: object[], font?: string }} input as for
 *   `buildPortfolioDocument`.
 */
export function buildCombinedDocument({ resume, phone, logo, projects, font }) {
  if (projects.length === 0) throw new Error('The combined file needs at least one project');
  return new Document({
    ...createStyles({ font }),
    ...COMBINED_PROPERTIES,
    sections: [
      {
        properties: { page: PAGE },
        footers: { default: buildFooter({ resume }) },
        children: [
          ...buildFirstBlock({ resume, phone, logo }),
          ...buildBody(resume),
          new Paragraph({ style: STYLE.part, children: [new TextRun(PART_TITLE)] }),
          ...buildPortfolioBody({ resume, projects }),
        ],
      },
    ],
  });
}
